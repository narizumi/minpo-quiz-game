def main():
    curation = json.loads(CURATION_PATH.read_text(encoding="utf-8"))
    converted = 0
    for topic in curation:
        for art in topic["articles"]:
            num = art["num"]
            existing = {"answer": art.pop("blank"), "cat": art.pop("cat")}
            extras = [{"answer": a, "cat": c} for a, c in ADDITIONS.get(num, [])]
            art["blanks"] = [existing] + extras
            converted += 1
    CURATION_PATH.write_text(
        json.dumps(curation, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print(f"Converted {converted} article entries to 'blanks' array.")
    counts = {}
    for topic in curation:
        for art in topic["articles"]:
            n = len(art["blanks"])
            counts[n] = counts.get(n, 0) + 1
    print("Blank-count distribution:", counts)


if __name__ == "__main__":
    main()
